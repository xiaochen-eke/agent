def ensure_knowledge_base_dir(base_path: str = None) -> str:
    """确保知识库目录存在"""
    if base_path is None:
        # 获取脚本所在目录的上级目录
        script_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        base_path = os.path.join(script_dir, "knowledge_base")
    
    os.makedirs(base_path, exist_ok=True)
    return base_path


def init_knowledge_base_files(kb_path: str = None) -> dict:
    """
    初始化知识库文件
    
    返回:
        dict: 创建的文件信息
    """
    if kb_path is None:
        kb_path = ensure_knowledge_base_dir()
    
    files_info = {}
    
    # 定义知识库文件
    knowledge_files = {
        "game_basics.md": GAME_BASICS,
        "survival_guide.md": SURVIVAL_GUIDE,
        "advanced_tactics.md": ADVANCED_TACTICS,
        "recipe_database.md": GAME_RECIPE_DB,
        "seasonal_guide.md": SEASONAL_GUIDE,
    }
    
    for filename, content in knowledge_files.items():
        filepath = os.path.join(kb_path, filename)
        
        # 如果文件已存在，检查是否需要更新
        if os.path.exists(filepath):
            with open(filepath, 'r', encoding='utf-8') as f:
                existing_content = f.read()
            if existing_content == content:
                files_info[filename] = {
                    'status': 'already_exists',
                    'path': filepath,
                    'size': len(content)
                }
                continue
        
        # 创建或更新文件
        try:
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            files_info[filename] = {
                'status': 'created',
                'path': filepath,
                'size': len(content)
            }
            print(f"✅ 创建知识库文件: {filename}")
        except Exception as e:
            files_info[filename] = {
                'status': 'error',
                'error': str(e),
                'path': filepath
            }
            print(f"❌ 创建失败: {filename} - {e}")
    
    return files_info


def verify_knowledge_base(kb_path: str = None) -> dict:
    """
    验证知识库完整性
    
    返回:
        dict: 验证结果
    """
    if kb_path is None:
        kb_path = ensure_knowledge_base_dir()
    
    expected_files = [
        "game_basics.md",
        "survival_guide.md", 
        "advanced_tactics.md",
        "recipe_database.md",
        "seasonal_guide.md"
    ]
    
    verification = {
        'total_files': len(expected_files),
        'found_files': 0,
        'missing_files': [],
        'total_size': 0,
        'path': kb_path
    }
    
    for filename in expected_files:
        filepath = os.path.join(kb_path, filename)
        if os.path.exists(filepath):
            verification['found_files'] += 1
            file_size = os.path.getsize(filepath)
            verification['total_size'] += file_size
        else:
            verification['missing_files'].append(filename)
    
    return verification


